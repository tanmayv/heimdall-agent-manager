# Run from repository root; standard library only.
import json
from pathlib import Path

schemas = json.loads(Path("src/contracts/fixtures/owner-local-schema.json").read_text())
odin = ["// Generated by scripts/generate-owner-local-contracts.py; do not edit.", "package contracts"]
ts = ["// Generated by scripts/generate-owner-local-contracts.py; do not edit.", "export const ownerSchemas = {"]
types = []
for kind, spec in schemas.items():
    fields = [s.split(":") for s in spec.split()]
    odin += ["Owner_" + kind.title() + " :: struct {"] + ["    " + name + ": string," for name, _ in fields] + ["}"]
    odin += ["@(private)", "owner_fields_" + kind + " := [?]Owner_Field{"] + ['    {"' + name + '", "' + typ + '"},' for name, typ in fields] + ["}"]
    ts += ["  " + kind + ": " + json.dumps(fields) + ","]
    types += ["export interface Owner" + kind.title() + " {"] + ["  " + name + ": string;" for name, _ in fields] + ["}"]
odin += ["owner_schema :: proc(kind: string) -> []Owner_Field {", "    switch kind {"]
odin += ['    case "' + kind + '": return owner_fields_' + kind + "[:]" for kind in schemas]
odin += ["    }", "    return nil", "}"]
ts += ["} as const;", "export type OwnerKind = keyof typeof ownerSchemas;", *types, "export interface OwnerDocuments {"]
ts += ["  " + kind + ": Owner" + kind.title() + ";" for kind in schemas] + ["}"]
Path("src/contracts/owner_schema.odin").write_text("\n".join(odin) + "\n")
Path("src/ui/api/ownerSchema.ts").write_text("\n".join(ts) + "\n")
